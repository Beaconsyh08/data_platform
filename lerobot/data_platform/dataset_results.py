"""Dataset-owned viewer results and checksummed, replayable sidecar replication.

Derived JSON/JSONL sidecars and edited viewer CSVs are replicated. Source data
and audit ledgers are never overwritten by this protocol.
"""

from __future__ import annotations

import base64
import contextlib
import fcntl
import hashlib
import json
import logging
import os
import re
import shutil
import time
import uuid
from dataclasses import dataclass
from pathlib import Path, PurePosixPath

from lerobot.data_platform.execution import atomic_json

MAX_RESULT_BYTES = 64 * 1024 * 1024
RESULT_DIRECTORIES = {"labeling", "tagging", "analysis", "annotations"}
REVIEW_FILES = {
    "flagged_episodes.json",
    "manual_flagged_episodes.json",
    "subtask_annotations.json",
    "trim_annotations.json",
    "prompt_assignments_pending.json",
}


def is_result_file(name: str) -> bool:
    path = PurePosixPath(name)
    if re.fullmatch(r"csv/episode_\d+(?:_ds\d+)?\.(?:csv|stages\.json)", name):
        return True
    return (
        not path.is_absolute()
        and str(path) == name
        and all(not part.startswith(".") for part in path.parts)
        and path.suffix in {".json", ".jsonl"}
        and path.name not in {"viewer_manifest.json", "operation_log.jsonl"}
        and (len(path.parts) == 1 or path.parts[0] in RESULT_DIRECTORIES)
    )


@contextlib.contextmanager
def result_lock(cache: Path):
    directory = cache.parent / ".result-locks"
    directory.mkdir(parents=True, exist_ok=True)
    with (directory / hashlib.sha256(str(cache).encode()).hexdigest()).open("a") as handle:
        fcntl.flock(handle, fcntl.LOCK_EX)
        yield


def result_path(static: Path, name: str) -> Path:
    if not is_result_file(name):
        raise ValueError("Unsupported result path")
    path = static / name
    if any(parent.is_symlink() for parent in [path, *path.parents] if parent != static.parent):
        raise ValueError("Result paths must not contain symbolic links")
    if not path.resolve().is_relative_to(static.resolve()):
        raise ValueError("Result path escapes the dataset cache")
    return path


@dataclass(frozen=True)
class ResultSnapshot:
    revision: str
    files: dict[str, dict]

    @classmethod
    def read(cls, static: Path, *, max_bytes: int | None = MAX_RESULT_BYTES) -> ResultSnapshot:
        files = {}
        total = 0
        paths = list(static.glob("*.json")) + list(static.glob("*.jsonl"))
        edited = static.parent / ".edited-csv.json"
        if edited.is_file():
            paths.extend(result_path(static, name) for name in json.loads(edited.read_text()))
        for directory in RESULT_DIRECTORIES:
            root = static / directory
            if not root.is_symlink():
                paths.extend(root.rglob("*.json"))
                paths.extend(root.rglob("*.jsonl"))
        for path in sorted(set(paths)):
            name = path.relative_to(static).as_posix()
            if not is_result_file(name):
                continue
            path = result_path(static, name)
            total += path.stat().st_size
            if max_bytes is not None and total > max_bytes:
                raise ValueError("Dataset result sidecars exceed the synchronization size limit")
            content = path.read_bytes()
            # Reject partially written results from an asynchronous producer; retry on the next poll.
            if path.suffix == ".json":
                json.loads(content)
            elif path.suffix == ".jsonl":
                for line in content.splitlines():
                    if line.strip():
                        json.loads(line)
            files[name] = {"sha256": hashlib.sha256(content).hexdigest(), "size": len(content)}
        revision = hashlib.sha256(json.dumps(files, sort_keys=True).encode()).hexdigest()
        return cls(revision, files)


def preserve_results(previous: Path, staged: Path) -> None:
    """Keep review decisions and results not regenerated by a cache rebuild."""
    if not (previous / "static").is_dir():
        return
    old_manifest = previous / "static/viewer_manifest.json"
    new_manifest = staged / "static/viewer_manifest.json"
    old_data = json.loads(old_manifest.read_text()) if old_manifest.is_file() else {}
    new_data = json.loads(new_manifest.read_text()) if new_manifest.is_file() else {}
    for key in ("root", "total_episodes", "total_frames", "episodes"):
        if key in old_data and key in new_data and old_data[key] != new_data[key]:
            return  # Episode identity changed; the old results remain in the backup.
    same_stages = old_data.get("task_config") == new_data.get("task_config")
    for name in ResultSnapshot.read(previous / "static", max_bytes=None).files:
        if not same_stages and (name.startswith("csv/") or name.startswith("subtask_annotations")):
            continue
        old = result_path(previous / "static", name)
        new = result_path(staged / "static", name)
        if (
            not new.exists()
            or name in REVIEW_FILES
            or "reviewed" in Path(name).name
            or name.startswith("csv/")
        ):
            new.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(old, new)
    edited = previous / ".edited-csv.json"
    if edited.is_file() and same_stages:
        shutil.copy2(edited, staged / edited.name)
    for name in ("operation_log.jsonl",):
        old, new = previous / "static" / name, staged / "static" / name
        if old.is_file() and not new.exists():
            shutil.copy2(old, new)


def mark_edited_csv(cache: Path, episode_id: int) -> None:
    path = cache / ".edited-csv.json"
    edited = set(json.loads(path.read_text())) if path.is_file() else set()
    for csv in (cache / "static/csv").glob(f"episode_{episode_id:06d}*.csv"):
        for file in (csv, csv.with_suffix(".stages.json")):
            if file.is_file():
                name = file.relative_to(cache / "static").as_posix()
                result_path(cache / "static", name)
                edited.add(name)
    atomic_json(path, sorted(edited))


def migrate_cache(previous: Path, target: Path) -> Path:
    """Move the registered authoritative cache out of a legacy per-job directory."""
    if previous.resolve() == target.resolve():
        return target
    if not (previous / "static/viewer_manifest.json").is_file():
        raise FileNotFoundError(previous / "static/viewer_manifest.json")
    if previous.is_symlink() or target.is_symlink():
        raise ValueError("Cache migration does not accept symbolic links")
    with result_lock(target):
        backup = target.with_name(f".{target.name}.migration-backup-{uuid.uuid4().hex}")
        if target.exists():
            os.replace(target, backup)
        try:
            os.replace(previous, target)
        except OSError:
            if backup.exists():
                os.replace(backup, target)
            raise
        # Keep old completed-job references valid; the real data now belongs to the dataset.
        previous.symlink_to(os.path.relpath(target, previous.parent), target_is_directory=True)
    return target


def sync_status(cache: Path) -> tuple[ResultSnapshot, dict]:
    snapshot = ResultSnapshot.read(cache / "static")
    path = cache / ".result-sync.json"
    state = json.loads(path.read_text()) if path.is_file() else {}
    if state.get("revision") != snapshot.revision:
        state = {"revision": snapshot.revision, "state": "pending", "updated_at": time.time()}
        atomic_json(path, state)
    return snapshot, state


def dataset_signature(manifest: dict) -> dict:
    return {
        **{key: manifest.get(key) for key in ("root", "total_episodes", "total_frames")},
        "episodes_sha256": hashlib.sha256(
            json.dumps(manifest.get("episodes"), sort_keys=True).encode()
        ).hexdigest(),
    }


def apply_results(cache: Path, bundle: dict, receipt: Path) -> None:
    """Validate the whole transfer before replacing files; acknowledge only after verification."""
    snapshot = ResultSnapshot(str(bundle["revision"]), dict(bundle["files"]))
    if hashlib.sha256(json.dumps(snapshot.files, sort_keys=True).encode()).hexdigest() != snapshot.revision:
        raise ValueError("Result manifest checksum mismatch")
    manifest = json.loads((cache / "static/viewer_manifest.json").read_text())
    if dataset_signature(manifest) != bundle["dataset"]:
        raise ValueError("Results do not match the local dataset cache; prepare the viewer again")
    content = {}
    total = 0
    for name, expected in snapshot.files.items():
        result_path(cache / "static", name)
        data = base64.b64decode(bundle["contents"][name], validate=True)
        total += len(data)
        if total > MAX_RESULT_BYTES:
            raise ValueError("Dataset result sidecars exceed the synchronization size limit")
        if len(data) != expected["size"] or hashlib.sha256(data).hexdigest() != expected["sha256"]:
            raise ValueError("Result file checksum mismatch")
        content[name] = data
    previous = json.loads(receipt.read_text()) if receipt.is_file() else {}
    backup = cache / ".result-sync-backups" / snapshot.revision
    if any(path.is_symlink() for path in [backup, backup.parent]):
        raise ValueError("Result backup directory must not be a symbolic link")
    for name in set(snapshot.files) | set(previous.get("files", {})):
        saved = backup / name
        if any(path.is_symlink() for path in [saved, *saved.parents] if path.is_relative_to(backup)):
            raise ValueError("Result backup paths must not contain symbolic links")
    for name in set(snapshot.files) | set(previous.get("files", {})):
        target = result_path(cache / "static", name)
        target.parent.mkdir(parents=True, exist_ok=True)
        saved = backup / name
        if target.is_file() and not saved.exists():
            saved.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(target, saved)
        if name not in content:
            target.unlink(missing_ok=True)
            continue
        temporary = target.with_name(f".{target.name}.{uuid.uuid4().hex}.tmp")
        try:
            with temporary.open("wb") as handle:
                handle.write(content[name])
                handle.flush()
                os.fsync(handle.fileno())
            os.replace(temporary, target)
        finally:
            temporary.unlink(missing_ok=True)
    for name, expected in snapshot.files.items():
        if hashlib.sha256(result_path(cache / "static", name).read_bytes()).hexdigest() != expected["sha256"]:
            raise ValueError("Published result checksum mismatch")
    atomic_json(
        cache / ".edited-csv.json", sorted(name for name in snapshot.files if name.startswith("csv/"))
    )
    atomic_json(receipt, {"revision": snapshot.revision, "files": snapshot.files})


def sync_agent_results(agent) -> None:
    from lerobot.data_platform.agent import _require_safe_output, _require_within
    from lerobot.data_platform.operation_log import append_operation_event

    directory = agent.state_path.parent / "executions"
    directory.mkdir(parents=True, exist_ok=True)
    with (directory / ".node-lock").open("a") as lock:
        try:
            fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            return  # A worker owns the dataset; the next idle poll retries.
        for location in agent.client.result_locations(agent.state):
            revision = location["revision"]
            try:
                source = _require_within(Path(location["root"]), agent.allowed_roots, "result dataset")
                cache = _require_safe_output(Path(location["output_dir"]), source, agent.writable_roots)
                manifest = json.loads((cache / "static/viewer_manifest.json").read_text())
                if manifest.get("root") != str(source):
                    raise ValueError("Local viewer cache belongs to another dataset")
                if dataset_signature(manifest) != location["dataset"]:
                    raise ValueError("Local viewer cache has different episode metadata")
                key = hashlib.sha256(location["location_id"].encode()).hexdigest()
                receipt = agent.state_path.parent / "result-sync" / f"{key}.json"
                recorded = json.loads(receipt.read_text()) if receipt.is_file() else {}
                intact = recorded.get("revision") == revision and all(
                    (path := result_path(cache / "static", name)).is_file()
                    and hashlib.sha256(path.read_bytes()).hexdigest() == item["sha256"]
                    for name, item in location["files"].items()
                )
                if intact and location["state"] == "synced":
                    continue
                if not intact:
                    bundle = agent.client.result_bundle(agent.state, location["location_id"])
                    revision = bundle["revision"]
                    apply_results(cache, bundle, receipt)
                    append_operation_event(
                        cache / "static",
                        "dataset.results.sync",
                        status="done",
                        source="agent",
                        dataset_roots=[source],
                        details={"revision": revision},
                    )
                agent.client.ack_results(agent.state, location["location_id"], revision)
            except Exception:
                logging.exception("Could not synchronize dataset results for %s", location["location_id"])
                try:
                    agent.client.ack_results(agent.state, location["location_id"], revision, error=True)
                except Exception:
                    logging.exception("Could not report dataset result synchronization failure")
